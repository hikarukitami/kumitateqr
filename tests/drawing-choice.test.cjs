const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/index.html'), 'utf8');
const segment = (from, to) => source.slice(source.indexOf(from), source.indexOf(to));
const ctx = vm.createContext({ esc: s => String(s ?? ''), cur: null, adminPin: '' });
vm.runInContext(segment('function drawingNeedsSelection(', 'function drawingBodyHtml('), ctx);
vm.runInContext(segment('function drawNoteHtml0(', 'function drawingHtml('), ctx);
vm.runInContext(segment('function drawingHtml(', 'const hasPos'), ctx);
const drawing = { no: 'K-X|RIGHT', drawNo: 'K-X', label: '右抜け', name: '小便器', url: 'https://example.com/a.pdf', points: [] };
ctx.cur = { drawMode: 'multi', drawings: [drawing], drawNote: '候補が複数あります' };
assert.equal(ctx.drawingNeedsSelection(ctx.cur), true);
assert.match(ctx.drawNoteHtml0(ctx.cur), /使用する図面を選ぶ/);
assert.match(ctx.drawingHtml(drawing, 0), /選んでから表示/);
assert.doesNotMatch(ctx.drawingHtml(drawing, 0), /別画面で開く/);
ctx.cur = { drawMode: 'explicit', drawings: [{ ...drawing, needsChoice: true }], drawNote: '左右を確認' };
assert.equal(ctx.drawingNeedsSelection(ctx.cur), true);
assert.match(ctx.drawNoteHtml0(ctx.cur), /左右を確認/);
assert.match(ctx.drawingHtml(ctx.cur.drawings[0], 0), /選んでから表示/);
ctx.cur = { drawMode: 'explicit', drawings: [drawing] };
assert.equal(ctx.drawingNeedsSelection(ctx.cur), false);
assert.match(ctx.drawingHtml(drawing, 0), /K-X（右抜け）/);
assert.match(ctx.drawingHtml(drawing, 0), /別画面で開く/);
console.log('PASS ambiguous drawings require a choice; selected variants show a readable label');
